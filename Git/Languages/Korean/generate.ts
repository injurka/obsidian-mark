// Функция генерации шаблона для обычных файлов
function generateNoteTemplate(title: string): string {
  // Убираем эмодзи из заголовка H1 (для красоты внутри файла)
  const cleanTitle = title.replace(/^[^\wА-Яа-яЁё]+\s*/, '');
  return `---
tags:
  - korean
  - draft
cssclasses:
  - kr-note
status: empty
---
# ${cleanTitle}

*Здесь будут ваши заметки...*

---
**Связанные темы:**
- [[Korean Knowledge Base|Главная страница]]
`;
}

async function buildKnowledgeBase() {
  console.log(`🚀 Начинаем генерацию базы знаний в папку: ${VAULT_DIR}...`);

  // Создаем корневую папку
  await mkdir(VAULT_DIR, { recursive: true });

  // 1. Создаем главный индексный файл
  const rootFilePath = join(VAULT_DIR, "Korean Knowledge Base.md");
  await Bun.write(rootFilePath, rootIndexContent);
  console.log(`✅ Создан корневой файл: Korean Knowledge Base.md`);

  // 2. Итерируемся по массиву путей и создаем папки/файлы
  let count = 0;
  for (const filePath of filePaths) {
    const fullPath = join(VAULT_DIR, filePath);
    const dirPath = dirname(fullPath);
    const fileName = basename(filePath, ".md");

    // Создаем вложенные папки, если их еще нет
    await mkdir(dirPath, { recursive: true });

    // Записываем markdown файл с базовым шаблоном
    await Bun.write(fullPath, generateNoteTemplate(fileName));
    count++;
  }

  console.log(`\n🎉 Готово! Успешно создано файлов: ${count + 1}`);
  console.log(`📁 Теперь вы можете открыть папку "${VAULT_DIR}" в Obsidian или Notion.`);
}

// Запуск скрипта
buildKnowledgeBase().catch((err) => {
  console.error("❌ Ошибка при генерации:", err);
});
