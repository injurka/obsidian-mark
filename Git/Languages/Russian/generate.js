// === 3. ФУНКЦИЯ ГЕНЕРАЦИИ ===
const rootDir = "Russian_Learning_Project";

function createStructure(basePath, items) {
  if (!fs.existsSync(basePath)) {
    fs.mkdirSync(basePath);
    console.log(`📁 Created folder: ${basePath}`);
  }

  items.forEach(item => {
    // Если это просто строка, значит это файл в текущей папке
    if (typeof item === 'string') {
      const filePath = path.join(basePath, item);
      const title = item.replace('.md', '');
      const defaultContent = `# ${title}\n\nTags: #russian #todo\n\n---\n\nЗаметки по теме...`;
      
      fs.writeFileSync(filePath, defaultContent);
      console.log(`📝 Created file: ${item}`);
    } 
    // Если это объект, это может быть папка с детьми или специальный файл
    else if (typeof item === 'object') {
      // Если есть поле 'content', это файл со специфическим контентом
      if (item.content) {
        const filePath = path.join(basePath, item.name);
        fs.writeFileSync(filePath, item.content);
        console.log(`⭐ Created MAIN file: ${item.name}`);
      } 
      // Если есть 'children', это папка
      else if (item.children) {
        const newPath = path.join(basePath, item.name);
        createStructure(newPath, item.children);
      }
    }
  });
}

